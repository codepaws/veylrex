//! Optional llama.cpp GGUF text-generation runner.
//!
//! The `runner` feature compiles the pinned `llama-cpp-2` native runtime from
//! its crate source. It does not download models or runtime artifacts.

#[cfg(feature = "runner")]
mod runner;

/// Provider name used by llama.cpp's GGML backend build.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Provider {
    /// CPU execution.
    Cpu,
    /// CUDA backend.
    Cuda,
    /// Vulkan backend.
    Vulkan,
    /// Metal backend.
    Metal,
}

/// Generation controls shared across llama.cpp requests.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GenerationOptions {
    /// Maximum number of generated tokens.
    pub max_tokens: u32,
    /// Context window size in tokens.
    pub context_size: u32,
    /// CPU worker threads used by llama.cpp.
    pub threads: u32,
}

impl GenerationOptions {
    /// Construct validated generation limits.
    pub fn new(max_tokens: u32, context_size: u32, threads: u32) -> Result<Self, InputError> {
        if max_tokens == 0 {
            return Err(InputError("max_tokens must be positive"));
        }
        if context_size == 0 {
            return Err(InputError("context_size must be positive"));
        }
        if threads == 0 || threads > i32::MAX as u32 {
            return Err(InputError("threads must be between 1 and i32::MAX"));
        }
        Ok(Self {
            max_tokens,
            context_size,
            threads,
        })
    }
}

impl Default for GenerationOptions {
    fn default() -> Self {
        Self {
            max_tokens: 128,
            context_size: 2048,
            threads: 4,
        }
    }
}

/// Invalid generation request fields.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct InputError(&'static str);

impl std::fmt::Display for InputError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(self.0)
    }
}
impl std::error::Error for InputError {}

/// Text generated by llama.cpp.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenerationOutput {
    /// Generated text, excluding the prompt.
    pub text: String,
    /// Requested and selected provider.
    pub provider: Provider,
}

/// Generate text from a local GGUF model with an explicit native provider.
#[cfg(feature = "runner")]
pub fn generate(
    model_path: impl AsRef<std::path::Path>,
    prompt: &str,
    options: GenerationOptions,
    provider: Provider,
) -> Result<GenerationOutput, Box<dyn std::error::Error>> {
    runner::generate(model_path.as_ref(), prompt, options, provider)
}

/// Build and runtime capability for one llama.cpp provider.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ProviderCapability {
    /// Provider name.
    pub provider: Provider,
    /// Whether a provider-specific build feature is present.
    pub compiled: bool,
    /// Runtime support result, when the runner was built and initialized.
    pub available: Option<bool>,
    /// Explanation for an unknown or unavailable state.
    pub reason: Option<String>,
}

/// Probe llama.cpp backend build/runtime support.
#[cfg(feature = "runner")]
pub fn capabilities() -> Vec<ProviderCapability> {
    runner::capabilities()
}

/// Return a CPU-only inventory when the native runner is not enabled.
#[cfg(not(feature = "runner"))]
pub fn capabilities() -> Vec<ProviderCapability> {
    vec![ProviderCapability {
        provider: Provider::Cpu,
        compiled: false,
        available: None,
        reason: Some("llama.cpp runner feature is not enabled".into()),
    }]
}

#[cfg(all(test, not(feature = "runner")))]
mod tests {
    use super::*;

    #[test]
    fn generation_options_reject_zero_tokens_and_context() {
        assert!(GenerationOptions::new(0, 128, 4).is_err());
        assert!(GenerationOptions::new(4, 0, 4).is_err());
    }

    #[test]
    fn generation_options_accept_positive_limits() {
        let options = GenerationOptions::new(16, 2048, 4).unwrap();
        assert_eq!(options.max_tokens, 16);
        assert_eq!(options.context_size, 2048);
        assert_eq!(options.threads, 4);
    }
}
